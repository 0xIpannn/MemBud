def _make_cache(path: Path, rows: list[tuple[str, str]]) -> None:
    connection = sqlite3.connect(path)
    try:
        connection.execute(
            "CREATE TABLE IF NOT EXISTS completions (cache_key TEXT PRIMARY KEY, payload TEXT NOT NULL)"
        )
        connection.executemany(
            "INSERT OR REPLACE INTO completions(cache_key, payload) VALUES (?, ?)", rows
        )
        connection.commit()
    finally:
        connection.close()


def test_load_cache_rows_tolerates_malformed_rows_and_stays_read_only(tmp_path):
    cache_path = tmp_path / "cache.sqlite3"
    _make_cache(
        cache_path,
        [
            ("good-key", json.dumps(_payload(ALL_PASS_CHECKS))),
            ("bad-json-key", "{not json"),
            ("not-object-key", json.dumps([1, 2, 3])),
        ],
    )
    before = hashlib.sha256(cache_path.read_bytes()).hexdigest()
    cache_path.chmod(0o444)  # prove the loader only needs read access
    loaded = analysis_module.load_cache_rows(cache_path)
    after = hashlib.sha256(cache_path.read_bytes()).hexdigest()

    assert set(loaded["rows"]) == {"good-key"}
    assert loaded["file_row_count"] == 3
    assert len(loaded["errors"]) == 2
    assert loaded["exists"] is True
    assert before == after


def test_load_cache_rows_missing_file_is_reported_not_raised(tmp_path):
    loaded = analysis_module.load_cache_rows(tmp_path / "does-not-exist.sqlite3")
    assert loaded == {"rows": {}, "errors": [], "exists": False, "file_row_count": 0}


def test_load_cache_rows_missing_table_is_reported_not_raised(tmp_path):
    cache_path = tmp_path / "empty.sqlite3"
    sqlite3.connect(cache_path).close()
    loaded = analysis_module.load_cache_rows(cache_path)
    assert loaded["rows"] == {}
    assert loaded["errors"]
    assert loaded["exists"] is True


def test_analysis_core_makes_no_network_calls(monkeypatch, tmp_path):
    def _forbidden_connection(*args, **kwargs):  # pragma: no cover - would fail the test
        raise AssertionError("network access attempted during cache-only analysis")

    monkeypatch.setattr("socket.socket", _forbidden_connection)
    cache_path = tmp_path / "cache.sqlite3"
    _make_cache(cache_path, [("good-key", json.dumps(_payload(ALL_PASS_CHECKS)))])
    loaded = analysis_module.load_cache_rows(cache_path)
    assert set(loaded["rows"]) == {"good-key"}

    cases, summary_rows, cache_rows = _build_fixture()
    analysis = analysis_module.analyse_cases(cases, summary_rows, cache_rows)
    assert analysis["coverage"]["full_cache_coverage"] is True


