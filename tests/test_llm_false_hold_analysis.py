"""Tests for the cache-only graph-LLM false-hold analysis.

Every test here is deterministic and performs no network or paid API call. The
real private cache is never required: cache access is exercised against a
throw-away SQLite file in ``tmp_path``, and the analysis core is fed synthetic
payload dictionaries. One test validates the committed analysis artifact, which
is regenerated by running ``scripts/analyze_llm_false_holds.py``.
"""
