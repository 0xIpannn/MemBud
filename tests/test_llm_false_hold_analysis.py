def test_derive_cache_key_is_deterministic_and_message_order_sensitive():
    first = {"role": "user", "content": "a"}
    second = {"role": "user", "content": "b"}
    assert analysis_module.derive_cache_key([first, second]) == analysis_module.derive_cache_key(
        [first, second]
    )
    assert analysis_module.derive_cache_key([first, second]) != analysis_module.derive_cache_key(
        [second, first]
    )


class _CapturingClient:
    """Records verifier messages, then fails; no network path exists."""

    model = "capturing-fake"
    configuration = {}

    def __init__(self) -> None:
        self.messages = None

    def complete_json(self, messages, validator=None):
        self.messages = list(messages)
        raise RuntimeError("network disabled in tests")


@pytest.mark.parametrize("representation", ["graph", "text"])
def test_derive_verifier_messages_matches_real_verify_with_llm(representation):
    transition = _transition(ACCEPT_RAW)
    client = _CapturingClient()
    result = verify_with_llm(transition, client, representation)
    # The fake always fails, so the real function must fail closed to UNCERTAIN.
    assert result.decision == "HOLD"
    assert {check.status for check in result.checks} == {"UNCERTAIN"}
    assert client.messages == analysis_module.derive_verifier_messages(
        transition, representation
    )
    info = analysis_module.derive_verifier_input(transition, representation)
    prefix = f"Representation: {representation}\nTransition input:\n"
    assert client.messages[1]["content"] == prefix + info["rendered"]
    assert info["chars"] == len(info["rendered"])
    if representation == "graph":
        assert info["graph_nodes"] is not None and info["graph_edges"] is not None
    else:
        assert info["graph_nodes"] is None and info["graph_edges"] is None


