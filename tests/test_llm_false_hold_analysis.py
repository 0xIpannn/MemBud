    artifact = json.loads(ARTIFACT_PATH.read_text(encoding="utf-8"))
    assert artifact["analysis_id"] == "graph-llm-false-hold-analysis-v1"

    coverage = artifact["coverage"]
    assert coverage["expected_cache_keys"] == 52
    assert coverage["cache_rows_loaded"] == 52
    assert coverage["matched_verifier_calls"] == 26
    assert coverage["expected_verifier_calls"] == 26
    assert coverage["matched_semantic_comparisons"] == 26
    assert coverage["expected_semantic_comparisons"] == 26
    assert coverage["missing"] == []
    assert coverage["unattributed_cache_keys"] == []
    assert coverage["full_cache_coverage"] is True
    assert coverage["all_assertions_passed"] is True
    assert coverage["cache_file_unchanged"] is True
    assert coverage["verifier_tokens_matching_cache"] == 26
    assert coverage["semantic_aggregates_matching_summary"] == 13

    assert {entry["case_id"] for entry in artifact["false_holds"]} == {
        "HELD-01",
        "HELD-02",
        "HELD-03",
        "HELD-07",
    }
    by_id = {entry["case_id"]: entry for entry in artifact["false_holds"]}
    assert by_id["HELD-01"]["graph_only"] is True
    assert by_id["HELD-03"]["graph_only"] is False
    assert all(
        any(check["name"] == "preservation" for check in entry["failed_checks"])
        for entry in artifact["false_holds"]
    )

