class _RecordingComparator:
    name = "recording-fake"

    def __init__(self) -> None:
        self.pairs: list[tuple[str, str]] = []

    def compare(self, claim_a: str, claim_b: str) -> SemanticRelation:
        self.pairs.append((claim_a, claim_b))
        return SemanticRelation.UNRELATED


