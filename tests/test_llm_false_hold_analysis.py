def test_sanitize_reason_collapses_whitespace_and_truncates():
    reason = "line one\nline two\twith\r\ncontrol \x07 chars"
    cleaned = analysis_module.sanitize_reason(reason, limit=40)
    assert "\n" not in cleaned and "\t" not in cleaned and "\r" not in cleaned
    assert len(cleaned) <= 40
    truncated = analysis_module.sanitize_reason("x" * 500, limit=50)
    assert len(truncated) <= 50
    assert truncated.endswith("...")
    assert analysis_module.sanitize_reason(None) == ""
    assert analysis_module.sanitize_reason(123) == ""


