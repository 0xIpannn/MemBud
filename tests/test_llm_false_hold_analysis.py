ROOT = Path(__file__).resolve().parents[1]
SCRIPT_PATH = ROOT / "scripts/analyze_llm_false_holds.py"
ARTIFACT_PATH = ROOT / "data/results/graph-llm-false-hold-analysis/analysis.json"


def _load_module():
    spec = importlib.util.spec_from_file_location(
        "analyze_llm_false_holds_under_test", SCRIPT_PATH
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    # Register before execution: the script defines a dataclass, and
    # dataclasses looks its module up in sys.modules while decorating.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


analysis_module = _load_module()


