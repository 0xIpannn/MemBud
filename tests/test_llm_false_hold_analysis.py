def _transition(raw: dict) -> Transition:
    return Transition.from_dict(raw)


def _payload(
    checks: list[dict],
    *,
    input_tokens: int = 100,
    output_tokens: int = 50,
    total_tokens: int = 150,
    request_attempts: int = 1,
    json_retries: int = 0,
    content: str = '{"checks": []}',
    model: str = "deepseek-flash",
) -> dict:
    """Cached payload shaped exactly like ``_save_cache`` (minus request_id)."""
    return {
        "json": {"checks": checks},
        "content": content,
        "model": model,
        "input_tokens": input_tokens,
        "output_tokens": output_tokens,
        "total_tokens": total_tokens,
        "request_id": "synthetic-request",
        "latency_ms": 12.5,
        "request_attempts": request_attempts,
        "json_retries": json_retries,
    }


def _semantic_payload(
    relation: str = "UNRELATED",
    *,
    input_tokens: int = 10,
    output_tokens: int = 5,
    total_tokens: int = 15,
    request_attempts: int = 1,
    json_retries: int = 0,
) -> dict:
    return {
        "json": {"relation": relation, "reason": "independent facts", "confidence": 0.9},
        "content": json.dumps({"relation": relation}),
        "model": "deepseek-flash",
        "input_tokens": input_tokens,
        "output_tokens": output_tokens,
        "total_tokens": total_tokens,
        "request_id": "synthetic-request",
        "latency_ms": 1.5,
        "request_attempts": request_attempts,
        "json_retries": json_retries,
    }


def _check_triples(payload: dict) -> list[dict]:
    return [
        {"name": check["name"], "status": check["status"], "reason_code": check["reason_code"]}
        for check in payload["json"]["checks"]
    ]


def _summary_row(
    condition: str,
    case_id: str,
    decision: str,
    *,
    checks: list[dict] | None = None,
    input_tokens: int = 0,
    output_tokens: int = 0,
    total_tokens: int = 0,
    json_retries: int = 0,
    attempts: int = 0,
) -> dict:
    return {
        "case_id": case_id,
        "condition": condition,
        "decision": decision,
        "status": "completed",
        "checks": checks or [],
        "usage": {
            "input_tokens": input_tokens,
            "output_tokens": output_tokens,
            "total_tokens": total_tokens,
            "json_retries": json_retries,
        },
        "attempts": attempts,
    }


def _semantic_summary_row(
    case_id: str, decision: str, *, checks: list[dict], tokens: tuple[int, int, int, int, int]
) -> dict:
    input_tokens, output_tokens, total_tokens, attempts, json_retries = tokens
    return _summary_row(
        "semantic",
        case_id,
        decision,
        checks=checks,
        input_tokens=input_tokens,
        output_tokens=output_tokens,
        total_tokens=total_tokens,
        json_retries=json_retries,
        attempts=attempts,
    )


def _case_spec(case_id: str, raw: dict, expected_decision: str) -> "analysis_module.CaseSpec":
    return analysis_module.CaseSpec(
        case_id=case_id,
        split="heldout",
        transition=_transition(raw),
        expected_decision=expected_decision,
        category="synthetic",
        fault_types=(),
    )


def _build_fixture() -> tuple[list, dict, dict]:
    """Two cases, complete cache and summary coverage, one graph false hold."""
    cases = [
        _case_spec("SYN-01", ACCEPT_RAW, "ACCEPT"),
        _case_spec("SYN-02", REVISE_RAW, "ACCEPT"),
    ]
    pair = analysis_module.semantic_pair_sequence(cases[0].transition)
    assert len(pair) == 1  # sanity check of the fixture, not of the code under test

    false_hold_checks = [
        dict(ALL_PASS_CHECKS[0]),
        {
            "name": "preservation",
            "status": "FAIL",
            "reason": (
                "The REVISE operation has null authorization, so the prior-record "
                "change is unauthorized."
            ),
            "reason_code": "PRIOR_RECORD_UNAUTHORIZED_CHANGE",
            "affected_ids": ["r1"],
        },
        dict(ALL_PASS_CHECKS[2]),
    ]

    cache_rows: dict[str, dict] = {}
    for representation in ("graph", "text"):
        accept_info = analysis_module.derive_verifier_input(
            cases[0].transition, representation
        )
        revise_info = analysis_module.derive_verifier_input(
            cases[1].transition, representation
        )
        cache_rows[
            analysis_module.derive_cache_key(accept_info["messages"])
        ] = _payload(ALL_PASS_CHECKS)
        cache_rows[
            analysis_module.derive_cache_key(revise_info["messages"])
        ] = _payload(false_hold_checks if representation == "graph" else ALL_PASS_CHECKS)
    claim_a, claim_b = pair[0]
    cache_rows[
        analysis_module.derive_cache_key(
            analysis_module.semantic_messages(claim_a, claim_b)
        )
    ] = _semantic_payload()

    semantic_pass = {
        "name": "semantic",
        "status": "PASS",
        "reason_code": "SEMANTIC_OK",
    }
    deterministic_pass = _check_triples(_payload(ALL_PASS_CHECKS))
    summary_rows = {
        ("graph", "SYN-01"): _summary_row(
            "graph",
            "SYN-01",
            "ACCEPT",
            checks=deterministic_pass,
            input_tokens=100,
            output_tokens=50,
            total_tokens=150,
            attempts=1,
        ),
        ("text", "SYN-01"): _summary_row(
            "text",
            "SYN-01",
            "ACCEPT",
            checks=deterministic_pass,
            input_tokens=100,
            output_tokens=50,
            total_tokens=150,
            attempts=1,
        ),
        ("graph", "SYN-02"): _summary_row(
            "graph",
            "SYN-02",
            "HOLD",
            checks=_check_triples(_payload(false_hold_checks)),
            input_tokens=100,
            output_tokens=50,
            total_tokens=150,
            attempts=1,
        ),
        ("text", "SYN-02"): _summary_row(
            "text",
            "SYN-02",
            "ACCEPT",
            checks=deterministic_pass,
            input_tokens=100,
            output_tokens=50,
            total_tokens=150,
            attempts=1,
        ),
        ("semantic", "SYN-01"): _semantic_summary_row(
            "SYN-01",
            "ACCEPT",
            checks=deterministic_pass + [semantic_pass],
            tokens=(10, 5, 15, 1, 0),
        ),
        ("semantic", "SYN-02"): _semantic_summary_row(
            "SYN-02",
            "ACCEPT",
            checks=deterministic_pass + [semantic_pass],
            tokens=(0, 0, 0, 0, 0),
        ),
    }
    return cases, summary_rows, cache_rows


